"""The dev stack never mounts prod's signing or data keys (F-03, CB-08, GAP-047).

``aura`` (prod) and ``aura-dev`` run side by side on one VPS and both resolve secrets from the
same ``deploy/secrets/`` directory. While dev mounted prod's ``jwt_secret``, any token dev minted
-- or anyone who compromised a dev container could mint -- was a valid prod session; with prod's
``data_encryption_keys`` dev could decrypt production rows. Dev now has its own files under the
same compose secret names (so its service mounts are unchanged), and these checks keep it that
way: a later edit that points dev back at a prod file fails here, not on the VPS.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

yaml = pytest.importorskip("yaml")

_DEPLOY = Path(__file__).resolve().parents[3] / "deploy"
_PROD = _DEPLOY / "docker-compose.prod.yml"
_DEV = _DEPLOY / "docker-compose.dev.yml"
_BOOTSTRAP = _DEPLOY / "scripts" / "bootstrap-secrets.sh"
_DEV_BRING_UP = _DEPLOY / "scripts" / "vps-dev-bring-up.sh"

#: Secrets whose holder can act as, or read the data of, the stack that owns them. Each must be a
#: different file per stack, generated by bootstrap-secrets.sh with the prod key's own generator.
_STACK_KEYS = {
    "jwt_secret": ("dev_jwt_secret", "generate", "jwt_secret"),
    "data_encryption_keys": ("dev_data_encryption_keys", "generate_fernet_key", "data_encryption_keys"),
}


def _secret_files(path: Path) -> dict[str, str]:
    assert path.is_file(), f"{path} is missing; these checks would pass vacuously"
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    return {name: str(Path(spec["file"])) for name, spec in (doc.get("secrets") or {}).items()}


def _gateway(path: Path, name: str) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))["services"][name]


@pytest.mark.parametrize("secret", sorted(_STACK_KEYS))
def test_dev_and_prod_resolve_stack_keys_to_different_files(secret: str) -> None:
    prod, dev = _secret_files(_PROD), _secret_files(_DEV)
    assert secret in prod and secret in dev, f"{secret} is no longer declared in both stacks"
    assert dev[secret] != prod[secret], f"dev's {secret} is prod's file {prod[secret]}"
    assert Path(dev[secret]).name == _STACK_KEYS[secret][0]


def test_dev_mounts_no_prod_stack_key_under_any_name() -> None:
    """Catches the key coming back under a renamed secret, not just the original name."""
    prod_key_files = {_secret_files(_PROD)[name] for name in _STACK_KEYS}
    leaked = {name: f for name, f in _secret_files(_DEV).items() if f in prod_key_files}
    assert not leaked, f"dev mounts prod key files: {leaked}"


def test_dev_gateway_still_reads_its_keys_through_the_same_mounts() -> None:
    """The fix changes only which file backs each name; the gateway wiring stays as it was."""
    service = _gateway(_DEV, "dev-gateway")
    assert {"jwt_secret", "data_encryption_keys"} <= set(service["secrets"])
    env = service["environment"]
    assert env["AURA_JWT_SECRET_FILE"] == "/run/secrets/jwt_secret"
    assert env["AURA_DATA_ENCRYPTION_KEYS_FILE"] == "/run/secrets/data_encryption_keys"


def test_both_gateways_forward_the_token_binding_settings() -> None:
    """Parity: an override set in .env must reach the gateway in either stack, or it is inert."""
    for path, name in ((_PROD, "gateway"), (_DEV, "dev-gateway")):
        env = _gateway(path, name)["environment"]
        for key in ("AURA_JWT_ISSUER", "AURA_JWT_AUDIENCE", "AURA_JWT_LEGACY_TOKENS_UNTIL"):
            assert env.get(key) == f"${{{key}:-}}", f"{path.name}/{name}: {key} not forwarded"


@pytest.mark.parametrize("secret", sorted(_STACK_KEYS))
def test_bootstrap_generates_the_dev_keys_like_the_prod_ones(secret: str) -> None:
    dev_file, generator, prod_file = _STACK_KEYS[secret]
    script = _BOOTSTRAP.read_text(encoding="utf-8")
    prod_line = re.search(rf"^{generator} {prod_file}\b(.*)$", script, re.M)
    dev_line = re.search(rf"^{generator} {dev_file}\b(.*)$", script, re.M)
    assert prod_line, f"bootstrap-secrets.sh no longer generates {prod_file} with {generator}"
    assert dev_line, (
        f"bootstrap-secrets.sh does not generate {dev_file} with {generator}; docker compose "
        "would refuse to start the dev gateway"
    )
    assert dev_line.group(1) == prod_line.group(1), f"{dev_file} is generated differently from {prod_file}"


def test_bootstrap_never_copies_a_prod_key_into_a_dev_file() -> None:
    script = _BOOTSTRAP.read_text(encoding="utf-8")
    for dev_file, _, prod_file in _STACK_KEYS.values():
        for line in script.splitlines():
            if line.lstrip().startswith("#"):
                continue
            assert not (prod_file in line and dev_file in line and re.search(r"\b(cp|cat|ln)\b", line)), line


def test_dev_bring_up_ensures_the_dev_key_files_exist() -> None:
    script = _DEV_BRING_UP.read_text(encoding="utf-8")
    bootstrap = script.find("bootstrap-secrets.sh\"")
    first_up = script.find("up -d")
    assert bootstrap != -1, "vps-dev-bring-up.sh does not run bootstrap-secrets.sh"
    assert bootstrap < first_up, "bootstrap-secrets.sh must run before the first dev `up`"
