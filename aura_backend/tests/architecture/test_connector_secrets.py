"""Connector credentials can only live in the vault (AP2, ADR-021).

A credential that reaches a descriptor, a twin, a blueprint or an approval payload is persisted,
digested, audited and shown to reviewers. The way to keep that from happening is structural: the
Track AP data model has no field that *could* hold a secret except ``secret_ref`` (an opaque vault
reference) and fields typed ``Credential`` (which never serialise or print). This walks the model
and fails on any other secret-looking field, so a future "just add an ``api_key`` option" fails
here rather than in an incident review.

It also pins the lazy-driver rule for ``adapters/connectors/``: importing a connector module must
not import its vendor driver (ADR-001), so the default suite needs none installed and nothing
connects at import time.
"""

from __future__ import annotations

import ast
import dataclasses
import re
import sys
import typing
from pathlib import Path

import pytest

from aura_core.domain import ausm, blueprint, connectors

CORE = Path(__file__).resolve().parents[2] / "aura_core"
STDLIB = set(sys.stdlib_module_names) | {"__future__"}

_SECRETISH = re.compile(r"pass|secret|token|credential|api_?key|private_?key", re.I)
#: The only secret-named fields the model may have, and why each is safe.
_ALLOWED = {
    ("ConnectorDescriptor", "secret_ref"): "opaque vault reference, generated by the vault",
    ("Credential", "_secret"): "the redacting wrapper itself",
}

MODEL_MODULES = (connectors, ausm, blueprint)


def _dataclasses() -> list[type]:
    found: list[type] = []
    for module in MODEL_MODULES:
        for value in vars(module).values():
            if isinstance(value, type) and dataclasses.is_dataclass(value) and value.__module__ == module.__name__:
                found.append(value)
    return found


@pytest.mark.parametrize("cls", _dataclasses(), ids=lambda c: c.__name__)
def test_no_field_can_hold_a_secret(cls: type) -> None:
    hints = typing.get_type_hints(cls)
    offenders = []
    for field in dataclasses.fields(cls):
        if not _SECRETISH.search(field.name) or (cls.__name__, field.name) in _ALLOWED:
            continue
        if "Credential" in repr(hints[field.name]):
            continue  # typed as the redacting wrapper (e.g. CallerIdentity.delegated_token)
        offenders.append(field.name)
    assert not offenders, (
        f"{cls.__name__} has secret-looking fields {offenders}: credentials belong in the vault "
        "(secret_ref) or in a Credential-typed field, never in the persisted model"
    )


def test_connector_adapters_import_their_drivers_lazily() -> None:
    violations: list[str] = []
    for module in sorted((CORE / "adapters" / "connectors").rglob("*.py")):
        tree = ast.parse(module.read_text(encoding="utf-8"), str(module))
        for node in tree.body:  # module scope only; function bodies are where drivers belong
            names: list[str] = []
            if isinstance(node, ast.Import):
                names = [a.name.split(".")[0] for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                names = [node.module.split(".")[0]]
            for name in names:
                if name not in STDLIB and name != "aura_core":
                    violations.append(f"{module.relative_to(CORE)}:{node.lineno} imports {name!r}")
    assert not violations, "connector drivers must be imported inside functions:\n  " + "\n  ".join(violations)
