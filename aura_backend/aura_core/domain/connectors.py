"""Connectors: how AURA reaches a connected system, and under whose authority (ADR-021).

A connector is registered by a Super Admin, approved against the digest of its descriptor, and
only then used. Three rules shape everything here:

* **No secret is ever part of a descriptor.** The descriptor holds the non-secret shape of the
  connection (kind, endpoint, options); the credential lives in the vault and the descriptor names
  it by an opaque ``secret_ref``. Endpoints carrying ``user:password@`` and options whose key
  looks like a secret are refused, so a credential cannot slip into a row, a digest, an approval
  payload, an audit record or a log line by way of the descriptor.
* **Identity mode is per connector.** A raw database or file share has no notion of the end
  user, so it runs under a vaulted service account whose permissions AURA enforces; an API that
  understands OAuth can instead receive the end user's own token per call (``DELEGATED``), which
  is never persisted.
* **Read-only in v1.** Nothing here can express a write; a connector whose credential *could*
  write is refused at activation (see ``ConnectorHealth.write_capable``).
"""

