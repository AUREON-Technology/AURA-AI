class ConnectorKind(str, enum.Enum):
    """The kinds of source system a connector can read (v1 set, ADR-021)."""

    POSTGRES = "postgres"
    MYSQL = "mysql"
    SQL_SERVER = "sql_server"
    OPENAPI = "openapi"
    FILES = "files"
    GIT = "git"
    #: AURA's own server-readable store, used by Project 0 (ADR-028).
    NATIVE = "native"

    def __str__(self) -> str:
        return self.value


class IdentityMode(str, enum.Enum):
    """Whose permissions a connector read runs under (ADR-021)."""

    #: The end user's own OIDC/OAuth token is forwarded per call; the target system enforces its
    #: own permissions and AURA's mapped policy is an additional filter. Never persisted.
    DELEGATED = "delegated"
    #: A vaulted service credential; discovered roles are mapped to AURA policy, and AURA is the
    #: enforcing authority.
    SERVICE_ACCOUNT = "service_account"

    def __str__(self) -> str:
        return self.value


class ConnectorState(str, enum.Enum):
    PENDING_APPROVAL = "pending_approval"
    ACTIVE = "active"
    DISABLED = "disabled"

    def __str__(self) -> str:
        return self.value


#: Same shape as an AUSM source id, because a connector *is* the source its elements come from.
CONNECTOR_ID_PATTERN = re.compile(r"^[a-z][a-z0-9_-]{0,63}$")
#: Vault references are opaque and generated by the vault; nothing about the secret leaks into one.
SECRET_REF_PATTERN = re.compile(r"^cred_[0-9a-f]{32}$")

#: Kinds with no notion of an end user: only a service account can be used (ADR-021, D5).
_SERVICE_ACCOUNT_ONLY = frozenset(
    {ConnectorKind.POSTGRES, ConnectorKind.MYSQL, ConnectorKind.SQL_SERVER, ConnectorKind.FILES, ConnectorKind.NATIVE}
)
#: Kinds that cannot work without a credential of their own.
_NEEDS_CREDENTIAL = frozenset({ConnectorKind.POSTGRES, ConnectorKind.MYSQL, ConnectorKind.SQL_SERVER})
#: Option by which a Super Admin attests that an OpenAPI connector's credential can only read
#: (AR-3). Bound into the descriptor digest like every option, so the approver signs it.
READ_ONLY_ATTESTED = "read_only_attested"
#: Options that mean something only for some kinds; anywhere else they are refused, not ignored.
_KIND_OPTIONS = {READ_ONLY_ATTESTED: frozenset({ConnectorKind.OPENAPI})}
_SECRETISH_KEY = re.compile(r"pass|secret|token|credential|api_?key|private_?key|auth", re.I)
_OPTION_KEY = re.compile(r"^[a-z][a-z0-9_]{0,63}$")
_MAX_OPTION_STR = 512
_MAX_ENDPOINT = 2048


@dataclass(frozen=True, slots=True)
class ConnectorDescriptor:
    """The non-secret description of one connector. Approval binds to :attr:`digest`."""

    id: str
    kind: ConnectorKind
    identity_mode: IdentityMode
    display_name: str
    endpoint: str
    options: Mapping[str, Any] = field(default_factory=dict)
    secret_ref: str | None = None
    max_concurrency: int = 4
    timeout_s: float = 15.0
    row_cap: int = 1000

    def __post_init__(self) -> None:
        if not CONNECTOR_ID_PATTERN.match(self.id):
            raise ValidationError("connector id must be a lower-case slug", details={"id": self.id})
        if not self.display_name.strip() or len(self.display_name) > 120:
            raise ValidationError("display_name must be 1-120 characters")
        if self.kind in _SERVICE_ACCOUNT_ONLY and self.identity_mode is not IdentityMode.SERVICE_ACCOUNT:
            raise ValidationError(
                f"a {self.kind} connector has no notion of an end user; use a service account",
                details={"kind": str(self.kind)},
            )
        _check_endpoint(self.endpoint)
        for key, value in self.options.items():
            if not isinstance(key, str) or not _OPTION_KEY.match(key):
                raise ValidationError("option keys must be snake_case", details={"key": key})
            if _SECRETISH_KEY.search(key):
                raise ValidationError(
                    "secrets belong in the credential vault, not in connector options",
                    details={"key": key},
                )
            if not (value is None or isinstance(value, (bool, int, float, str))):
                raise ValidationError("option values must be scalars", details={"key": key})
            if isinstance(value, str) and len(value) > _MAX_OPTION_STR:
                raise ValidationError("option value too long", details={"key": key})
            if key in _KIND_OPTIONS and self.kind not in _KIND_OPTIONS[key]:
                raise ValidationError(f"option {key!r} does not apply to a {self.kind} connector",
                                      details={"key": key, "kind": str(self.kind)})
        if READ_ONLY_ATTESTED in self.options and not isinstance(self.options[READ_ONLY_ATTESTED], bool):
            raise ValidationError(f"{READ_ONLY_ATTESTED} must be true or false")
        if self.secret_ref is not None and not SECRET_REF_PATTERN.match(self.secret_ref):
            raise ValidationError("secret_ref is not a vault reference")
        if not 1 <= self.max_concurrency <= 32:
            raise ValidationError("max_concurrency must be 1..32")
        if not 0.5 <= self.timeout_s <= 120.0:
            raise ValidationError("timeout_s must be 0.5..120 seconds")
        if not 1 <= self.row_cap <= 10_000:
            raise ValidationError("row_cap must be 1..10000")
        object.__setattr__(self, "options", MappingProxyType(dict(self.options)))

    @property
    def needs_credential(self) -> bool:
        return self.kind in _NEEDS_CREDENTIAL and self.identity_mode is IdentityMode.SERVICE_ACCOUNT

    @property
    def digest(self) -> str:
        """``sha256:<hex>`` of the canonical descriptor: what a registration approval binds to.

        ``secret_ref`` is included, so swapping the vaulted credential after approval (a different
        ref) invalidates it; the credential's own bytes are not, because they are never here.
        """
        return content_digest(self)


def _check_endpoint(endpoint: str) -> None:
    if not isinstance(endpoint, str) or not endpoint.strip() or len(endpoint) > _MAX_ENDPOINT:
        raise ValidationError(f"endpoint must be 1-{_MAX_ENDPOINT} characters")
    if any(ch.isspace() or ord(ch) < 32 for ch in endpoint):
        raise ValidationError("endpoint must not contain whitespace or control characters")
    if "://" in endpoint:
        parts = urlsplit(endpoint)
        if parts.username is not None or parts.password is not None:
            raise ValidationError(
                "endpoint must not embed credentials; put them in the credential vault"
            )
        if parts.query and _SECRETISH_KEY.search(parts.query):
            raise ValidationError("endpoint query must not carry credentials")


@dataclass(frozen=True, slots=True)
class ConnectorRecord:
    """A registered connector and where it is in its lifecycle."""

    descriptor: ConnectorDescriptor
    state: ConnectorState
    registered_by: str
    registered_at: datetime
    approval_id: str | None = None
    activated_by: str | None = None
    activated_at: datetime | None = None

    @property
    def id(self) -> str:
        return self.descriptor.id


class HealthStatus(str, enum.Enum):
    HEALTHY = "healthy"
    DEGRADED = "degraded"
    UNHEALTHY = "unhealthy"

    def __str__(self) -> str:
        return self.value


@dataclass(frozen=True, slots=True)
class ConnectorHealth:
    """One health check. ``reason`` is a low-cardinality code, never vendor text.

    ``write_capable`` is ``True`` when the credential could change the target system (any write
    privilege, ownership, or an elevated role), ``False`` when the connector checked and found
    none, and ``None`` when the kind cannot tell. Activation requires ``False``.
    """

    status: HealthStatus
    reason: str = "ok"
    write_capable: bool | None = None
    latency_ms: float = 0.0
    findings: tuple[str, ...] = ()

    @property
    def ok(self) -> bool:
        return self.status is HealthStatus.HEALTHY


@dataclass(frozen=True, slots=True)
class Credential:
    """A secret in memory, for the few lines between the vault and a driver call.

    It cannot be printed or formatted -- ``repr``/``str``/``format`` all redact -- so passing one
    to a logger, an exception message or an f-string leaks nothing. :meth:`reveal` is the only way
    to the bytes, and is greppable in review.
    """

    _secret: str = field(repr=False)

    def __post_init__(self) -> None:
        if not isinstance(self._secret, str) or not self._secret:
            raise ValidationError("a credential must be a non-empty string")

    def reveal(self) -> str:
        return self._secret

    def __repr__(self) -> str:
        return "Credential(<redacted>)"

    def __str__(self) -> str:
        return "<redacted credential>"

    def __format__(self, spec: str) -> str:
        return str(self)


@dataclass(frozen=True, slots=True)
class CallerIdentity:
    """Who a connector call is made for (ADR-021).

    ``delegated_token`` carries the end user's own token for a ``DELEGATED`` connector; it is
    redacted from ``repr`` and must never be stored -- no store in this codebase takes a
    ``CallerIdentity``.
    """

    user_id: UserId
    roles: frozenset[str] = frozenset()
    delegated_token: Credential | None = field(default=None, repr=False)


#: Where a caller's token for one delegated connector travels in ``ToolContext.credentials``:
#: per turn, in memory, keyed by connector id. Nothing stores a ``ToolContext``.
CONNECTOR_TOKEN_PREFIX = "connector:"


def connector_token_key(connector_id: str) -> str:
    return f"{CONNECTOR_TOKEN_PREFIX}{connector_id}"


#: A delegated token this close to expiry is refused rather than sent: the target would accept
#: it now and reject the next call of the same turn, mid-answer.
DELEGATED_EXPIRY_LEEWAY_S = 30.0


def bearer_token_expiry(token: str) -> float | None:
    """The ``exp`` claim of a JWT-shaped bearer token (seconds since the epoch), else ``None``.

    Read without verifying the signature: this is not authentication -- the target system
    verifies its own token -- only a way to refuse a token that is plainly expired before it is
    sent, with a re-authentication hint, instead of after a round trip. An opaque token (not three
    base64url segments, or no numeric ``exp``) has no knowable expiry and is left to the target.
    """
    parts = token.split(".")
    if len(parts) != 3 or not parts[1]:
        return None
    try:
        payload = json.loads(base64.urlsafe_b64decode(parts[1] + "=" * (-len(parts[1]) % 4)))
    except (ValueError, TypeError):
        return None
    exp = payload.get("exp") if isinstance(payload, dict) else None
    if isinstance(exp, bool) or not isinstance(exp, (int, float)):
        return None
    return float(exp)
