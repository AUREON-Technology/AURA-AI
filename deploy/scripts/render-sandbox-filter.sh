#!/bin/sh
# render-sandbox-filter.sh -- turn AURA_SANDBOX_ALLOWED_EGRESS_HOSTS into tinyproxy's `filter`.
#
# The egress allowlist an engineer-agent workspace is held to is the tinyproxy `filter` file
# (deploy/sandbox/filter): the workspace network is `internal`, the proxy is the only way out, and
# `FilterDefaultDeny Yes` means a host not in that file is refused. Until now the setting
# AURA_SANDBOX_ALLOWED_EGRESS_HOSTS was parsed by the gateway and read by nothing, so the only way
# to allow another host was to edit the file by hand. This script makes the setting real:
#
#     filter(out) = filter(base) + one anchored, escaped line per validated host
#
# With no hosts the output is the base file unchanged, so a deployment that never sets the
# variable behaves exactly as before.
#
# Usage:
#   render-sandbox-filter.sh [--base FILE] [--out FILE] [--hosts "a.example,b.example"] [--check]
#
#   --base FILE   the static filter to start from   (default: ../sandbox/filter next to this script)
#   --out FILE    write here, atomically, only if every host validated   (default: stdout)
#   --hosts LIST  comma/space/newline separated hosts   (default: $AURA_SANDBOX_ALLOWED_EGRESS_HOSTS)
#   --check       validate the hosts and exit; write nothing
#
# A host must be a bare DNS name: letters, digits, hyphens and dots, lower-cased, at least two
# labels, each label 1-63 characters, no wildcard, scheme, path, port or credentials, and not an
# IP address (an allowlist of addresses is how a workspace gets pointed at the internal network).
# `*.example.com` is refused on purpose: a wildcard is "every host the owner of that domain will
# ever create", which is not an entry anyone can justify line by line. List the hosts.
#
# Exit status: 0 ok; 2 a host or an argument is invalid (the message names it); 1 anything else.
# POSIX sh and sed/tr only -- it runs in the tinyproxy image, which has nothing else.
#
# Idempotent: a generated section already present in --base is replaced, never doubled, so
# rendering over its own output gives the same bytes.

set -eu
# A host that contained `*` must never be glob-expanded against the working directory.
set -f

BEGIN_MARK='# --- BEGIN hosts from AURA_SANDBOX_ALLOWED_EGRESS_HOSTS (generated by render-sandbox-filter.sh; do not edit) ---'
END_MARK='# --- END generated hosts ---'
MAX_HOSTS=100

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
base="$here/../sandbox/filter"
out=""
hosts_arg=""
have_hosts_arg=0
check_only=0

die() {
    printf 'render-sandbox-filter: %s\n' "$1" >&2
    exit "${2:-2}"
}

while [ $# -gt 0 ]; do
    case $1 in
        --base)  [ $# -ge 2 ] || die "--base needs a file"; base=$2; shift 2 ;;
        --out)   [ $# -ge 2 ] || die "--out needs a file"; out=$2; shift 2 ;;
        --hosts) [ $# -ge 2 ] || die "--hosts needs a list"; hosts_arg=$2; have_hosts_arg=1; shift 2 ;;
        --check) check_only=1; shift ;;
        -h|--help) sed -n '2,/^set -eu/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
        *) die "unknown argument: $1" ;;
    esac
done

if [ "$have_hosts_arg" -eq 1 ]; then
    raw=$hosts_arg
else
    raw=${AURA_SANDBOX_ALLOWED_EGRESS_HOSTS:-}
fi

# Why `$1` is not an acceptable host, or nothing (and status 0) when it is. Prints the reason.
host_problem() {
    h=$1
    case $h in
        *\**) echo "wildcards are not supported; list each host"; return 1 ;;
        *://*|*/*) echo "give a bare host name, not a URL or a path"; return 1 ;;
        *@*) echo "credentials are not allowed in a host"; return 1 ;;
        *:*) echo "a port is not allowed (the proxy only ever connects to 443)"; return 1 ;;
    esac
    case $h in
        *[!a-z0-9.-]*) echo "only lower-case letters, digits, hyphens and dots are allowed"; return 1 ;;
    esac
    case $h in
        .*|*.|-*|*-|*..*|*.-*|*-.*) echo "malformed (empty label, or a label starting or ending with a hyphen)"; return 1 ;;
    esac
    if [ "${#h}" -gt 253 ]; then
        echo "longer than 253 characters"; return 1
    fi
    old_ifs=$IFS
    IFS=.
    # shellcheck disable=SC2086 -- splitting on dots is the point; globbing is off (set -f)
    set -- $h
    IFS=$old_ifs
    if [ $# -lt 2 ]; then
        echo "needs at least two labels (a single name such as 'localhost' is an internal host)"; return 1
    fi
    for label in "$@"; do
        if [ "${#label}" -gt 63 ]; then
            echo "a label is longer than 63 characters"; return 1
        fi
        last=$label
    done
    case $last in
        *[!0-9]*) : ;;
        *) echo "an IP address is not a host name"; return 1 ;;
    esac
    return 0
}

validated=""
count=0
# Commas, tabs and newlines all separate hosts, as they would in an .env file or a YAML list.
list=$(printf '%s' "$raw" | tr ',\t\r\n' '    ')
for entry in $list; do
    original=$entry
    lowered=$(printf '%s' "$entry" | tr 'A-Z' 'a-z')
    if ! reason=$(host_problem "$lowered"); then
        die "invalid host '$original': $reason"
    fi
    escaped=$(printf '%s' "$lowered" | sed 's/\./\\./g')
    line="^${escaped}\$"
    case "
$validated
" in
        *"
$line
"*) continue ;;  # a duplicate is harmless; keep the first
    esac
    count=$((count + 1))
    [ "$count" -le "$MAX_HOSTS" ] || die "more than $MAX_HOSTS hosts; an allowlist that long is not one anyone reviews"
    validated="${validated}
${line}"
done

[ "$check_only" -eq 0 ] || exit 0

[ -r "$base" ] || die "cannot read the base filter: $base" 1

render() {
    # The base without any previously generated section...
    sed "/^# --- BEGIN hosts from AURA_SANDBOX_ALLOWED_EGRESS_HOSTS/,/^# --- END generated hosts ---\$/d" "$base"
    # ...plus this run's hosts, if any.
    if [ "$count" -gt 0 ]; then
        printf '%s\n' "$BEGIN_MARK"
        printf '%s\n' "$validated" | sed '1{/^$/d;}'
        printf '%s\n' "$END_MARK"
    fi
}

if [ -z "$out" ]; then
    render
else
    tmp="$out.tmp.$$"
    trap 'rm -f "$tmp"' EXIT INT TERM
    render > "$tmp"
    chmod 644 "$tmp"
    mv -f "$tmp" "$out"
    trap - EXIT INT TERM
fi
