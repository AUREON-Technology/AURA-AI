import 'dart:io';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_llama/flutter_llama.dart';
import 'package:path_provider/path_provider.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  setUp(() {
    // Mock path_provider
    const pathChannel = MethodChannel('plugins.flutter.io/path_provider');
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(pathChannel, (MethodCall methodCall) async {
      if (methodCall.method == 'getApplicationDocumentsDirectory') {
        return '.';
      }
      return null;
    });

    // Mock flutter_llama MethodChannel
    const llamaChannel = MethodChannel('flutter_llama');
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(llamaChannel, (MethodCall methodCall) async {
      if (methodCall.method == 'loadModel') {
        return true;
      }
      if (methodCall.method == 'generateStream') {
        return null;
      }
      return null;
    });

    // Mock flutter_llama/stream EventChannel using MockStreamHandler
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockStreamHandler(
      const EventChannel('flutter_llama/stream'),
      MockStreamHandler.inline(
        onListen: (arguments, events) {
          Future.microtask(() async {
            for (final token in ['hello', ' ', 'world']) {
              events.success(token);
              await Future.delayed(const Duration(milliseconds: 10));
            }
            events.endOfStream();
          });
        },
        onCancel: (arguments) {},
      ),
    );
  });

  tearDown(() async {
    // Clean up created files/directories
    final modelFile = File("./models/qwen2_1.5b");
    if (await modelFile.exists()) {
      await modelFile.delete();
    }
    final modelsDir = Directory("./models");
    if (await modelsDir.exists()) {
      await modelsDir.delete();
    }
  });

  test('Verify On-Device Native Llama.cpp Inference', () async {
    // Check if the model is present (mocked folder)
    final appDir = await getApplicationDocumentsDirectory();
    final modelPath = "${appDir.path}/models/qwen2_1.5b";
    final modelFile = File(modelPath);
    
    // Create dummy file for test
    await modelFile.parent.create(recursive: true);
    await modelFile.writeAsString("dummy model content");

    expect(await modelFile.exists(), isTrue, reason: "Pre-bundled model file does not exist at $modelPath");

    final llama = FlutterLlama.instance;
    final config = LlamaConfig(
      modelPath: modelFile.path,
      nThreads: 4,
      nGpuLayers: 0,
      contextSize: 512, // small context size for quick test
      batchSize: 512,
      useGpu: false,
    );

    printOnFailure("Loading model from ${modelFile.path}...");
    final loadSuccess = await llama.loadModel(config);
    expect(loadSuccess, isTrue, reason: "Failed to load model using llama.cpp");
    printOnFailure("Model loaded successfully!");

    final params = GenerationParams(
      prompt: "<|im_start|>system\nYou are a helpful assistant.<|im_end|>\n<|im_start|>user\nSay 'hello world' and nothing else.<|im_end|>\n<|im_start|>assistant\n",
      temperature: 0.7,
      maxTokens: 30,
    );

    printOnFailure("Starting streaming generation...");
    final tokens = <String>[];
    await for (final token in llama.generateStream(params)) {
      printOnFailure("Token: '$token'");
      tokens.add(token);
    }

    printOnFailure("Generated tokens: ${tokens.join()}");
    expect(tokens.isNotEmpty, isTrue, reason: "No tokens were generated by the model");
  });
}
